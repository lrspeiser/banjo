"""Tables for src/numeric/PortableMathTables.hpp: each value as a double-double
(hi = the double nearest the value, lo = the double nearest what remains),
computed with mpmath at 240 bits."""
from mpmath import mp, mpf
from mpmath.libmp import to_float
mp.prec = 240
def dd(v):
    hi = to_float(v._mpf_, rnd='n')
    lo = to_float((v - mpf(hi))._mpf_, rnd='n')
    return hi, lo
def table(name, values, comment):
    rows = [f"    {{{h.hex()}, {l.hex()}}}," for h, l in (dd(v) for v in values)]
    return f"// {comment}\ninline constexpr Pair {name}[{len(values)}] = {{\n" + "\n".join(rows) + "\n};\n"
out = []
out.append(table("kExp2Sixtyfourths", [mp.mpf(2) ** (mpf(j) / 64) for j in range(64)], "2^(j/64), j = 0..63"))
out.append(table("kLogOnePlus", [mp.log(1 + mpf(i) / 128) for i in range(129)], "ln(1 + i/128), i = 0..128"))
out.append(table("kSinSixtyfourths", [mp.sin(mpf(j) / 64) for j in range(52)], "sin(j/64), j = 0..51"))
out.append(table("kCosSixtyfourths", [mp.cos(mpf(j) / 64) for j in range(52)], "cos(j/64), j = 0..51"))
out.append(table("kAtanSixtyfourths", [mp.atan(mpf(j) / 64) for j in range(65)], "atan(j/64), j = 0..64"))
hdr = '''#pragma once

// Tables for numeric/PortableMath.hpp, generated by
// scripts/generate-portable-math-tables.py (mpmath, 240 bits): each value is a
// double-double, hi the double nearest it and lo the double nearest the rest.
// Regenerate rather than edit.

namespace banjo::pm::tables {

struct Pair {
    double hi, lo;
};

''' + "\n".join(out) + '''
} // namespace banjo::pm::tables
'''
import sys
open(sys.argv[1], 'w', newline='\n').write(hdr)
print("wrote", sys.argv[1])
